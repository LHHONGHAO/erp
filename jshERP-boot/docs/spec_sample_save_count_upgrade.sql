-- =====================================================
-- 规格值一致性判定（标准值学习）
-- 背景：
--   1. 某些属性长期只有一个或少数几个固定值（安全类别、执行标准、成分等），
--      可判定为「一致性属性」，识别时把 OCR 误差文本归一到这些标准值；
--   2. 判定依据是历史「保存采纳」的分布，因此样本需要记录被采纳次数；
--   3. 数据呈多样性的属性（花色、款式）不自动归一，避免误改。
-- 说明：一次性 ALTER，重复执行会报「列已存在」，属正常。
-- =====================================================

ALTER TABLE `jsh_spec_value_sample`
  ADD COLUMN `save_count` INT NOT NULL DEFAULT 1 COMMENT '该标准写法被保存采纳的次数，用于一致性判定' AFTER `hit_count`;
